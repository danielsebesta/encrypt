// Generates src/lib/icons.ts from src/lib/iconManifest.ts and
// @iconify-json/tabler. Prefers <name>-filled. Run: pnpm run build:icons
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ICONS, OUTLINE } from '../src/lib/iconManifest.ts';

const root = new URL('../', import.meta.url);
const file = (p) => fileURLToPath(new URL(p, root));

const data = JSON.parse(readFileSync(file('node_modules/@iconify-json/tabler/icons.json'), 'utf8'));

function resolve(name) {
  let current = name;
  for (let depth = 0; depth < 8; depth += 1) {
    if (data.icons[current]) return current;
    const alias = data.aliases?.[current];
    if (!alias?.parent) return null;
    current = alias.parent;
  }
  return null;
}

const problems = [];
const bodies = {};
const chosen = new Map();
const fallbacks = [];

for (const key of Object.keys(OUTLINE)) {
  if (!(key in ICONS)) problems.push(`OUTLINE key "${key}" is not in ICONS`);
}

for (const [key, base] of Object.entries(ICONS)) {
  const filledName = `${base}-filled`;
  const filled = resolve(filledName);
  const outline = resolve(base);
  const forced = Object.prototype.hasOwnProperty.call(OUTLINE, key);
  if (forced) {
    if (!outline) {
      problems.push(`${key}: outline "${base}" not found in @iconify-json/tabler`);
      continue;
    }
    bodies[key] = data.icons[outline].body;
    fallbacks.push({ key, icon: outline, reason: OUTLINE[key] });
  } else if (filled) {
    bodies[key] = data.icons[filled].body;
    const list = chosen.get(filled) ?? [];
    list.push(key);
    chosen.set(filled, list);
    continue;
  } else if (outline) {
    bodies[key] = data.icons[outline].body;
    fallbacks.push({ key, icon: outline, reason: `no ${filledName} in @iconify-json/tabler` });
  } else {
    problems.push(`${key}: neither "${filledName}" nor "${base}" found in @iconify-json/tabler`);
    continue;
  }
  const icon = fallbacks[fallbacks.length - 1].icon;
  const list = chosen.get(icon) ?? [];
  list.push(key);
  chosen.set(icon, list);
}

for (const [icon, keys] of chosen) {
  if (keys.length > 1) console.warn(`note: ${icon} is shared by ${keys.join(', ')}`);
}

if (problems.length) {
  console.error(`build:icons failed:\n${problems.map((p) => `  - ${p}`).join('\n')}`);
  process.exit(1);
}

const lines = Object.entries(bodies).map(([key, body]) => `  ${JSON.stringify(key)}: ${JSON.stringify(body)},`);
const out = `// Generated by scripts/build-icons.mjs, do not edit.
import type { IconName } from './iconManifest';

export const TABLER: Record<IconName, string> = {
${lines.join('\n')}
};

export const ICON_CREDIT = {
  name: 'Tabler Icons',
  author: 'Paweł Kuna',
  license: 'MIT',
  licenseUrl: 'https://github.com/tabler/tabler-icons/blob/main/LICENSE',
  sourceUrl: 'https://github.com/tabler/tabler-icons',
} as const;
`;

writeFileSync(file('src/lib/icons.ts'), out);

const filledCount = Object.keys(bodies).length - fallbacks.length;
console.log(`build:icons: wrote ${Object.keys(bodies).length} Tabler bodies (${filledCount} filled, ${fallbacks.length} outline)`);
if (fallbacks.length) {
  console.log('outline fallback:');
  for (const item of fallbacks) console.log(`  - ${item.key} -> ${item.icon}: ${item.reason}`);
}
