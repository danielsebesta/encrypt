/**
 * Builds the per-language byte-frequency models for the chat cipher's static Huffman compression
 * (src/lib/chatCipher/textModel.ts). Run with: pnpm exec tsx scripts/build-chat-cipher-models.ts
 *
 * Sources: cleaned chat bursts in data/chat-cipher-<lang>/clean/all.clean.jsonl (en, de, es, fr, sk, pl).
 * Czech has no cleaned corpus in the repo, so its model comes from the cs word table: the unigram words
 * weighted by their shares, joined by spaces. Every byte keeps a weight of at least 1, so the coder can
 * always encode any payload, even text that does not fit the language.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { parseCoverTable } from '../src/lib/chatCipher/tableCodec';
import { COVER_TABLES, COVER_LANGS, type CoverLang } from '../src/lib/chatCipher/coverTable';

const LANGS: CoverLang[] = ['cs', ...COVER_LANGS.filter(l => l !== 'cs')];

function bytesFromCorpus(lang: CoverLang): Uint8Array {
  const rows = readFileSync(`data/chat-cipher-${lang}/clean/all.clean.jsonl`, 'utf8').split(/\r?\n/).filter(Boolean);
  const messages: string[] = [];
  for (const row of rows) {
    const parsed = JSON.parse(row) as { messages?: string[] };
    if (Array.isArray(parsed.messages)) messages.push(...parsed.messages);
  }
  return new TextEncoder().encode(messages.join('\n'));
}

function bytesFromCsTable(): Uint8Array {
  const packed = readFileSync(`public${COVER_TABLES.cs.url}`);
  const table = parseCoverTable(gunzipSync(packed));
  const text: string[] = [];
  for (let e = 0; e < table.unigramWords.length; e++) {
    const word = table.words[table.unigramWords[e]];
    const share = table.unigramShares[e];
    for (let n = 0; n < share; n++) text.push(word);
  }
  return new TextEncoder().encode(text.join(' '));
}

function modelFor(source: Uint8Array): { weights: Uint16Array; entropyBitsPerByte: number; bytes: number } {
  const counts = new Float64Array(256);
  for (const byte of source) counts[byte]++;
  const max = Math.max(...counts);
  const weights = new Uint16Array(256);
  for (let b = 0; b < 256; b++) weights[b] = Math.max(1, Math.round((counts[b] / max) * 30000));
  let entropy = 0;
  let total = 0;
  for (const b of counts) total += b;
  for (let b = 0; b < 256; b++) {
    const p = counts[b] / total;
    if (p > 0) entropy -= p * Math.log2(p);
  }
  return { weights, entropyBitsPerByte: entropy, bytes: source.length };
}

const lines: string[] = [];
lines.push('// Generated by scripts/build-chat-cipher-models.ts; do not edit.');
lines.push("import type { CoverLang } from './coverTable';");
lines.push('');
lines.push('/** Byte weights for the static per-language Huffman coder, quantised over the sorted corpus of each language. */');
lines.push('export const TEXT_MODELS: Record<CoverLang, Uint16Array> = {');
for (const lang of LANGS) {
  const source = lang === 'cs' ? bytesFromCsTable() : bytesFromCorpus(lang);
  const { weights, entropyBitsPerByte, bytes } = modelFor(source);
  if (source.length < 100_000) throw new Error(`${lang}: corpus too small (${source.length} bytes)`);
  console.log(`${lang}: ${bytes} source bytes, model entropy ${entropyBitsPerByte.toFixed(2)} bits/byte`);
  lines.push(`  ${lang}: new Uint16Array([${Array.from(weights).join(', ')}]),`);
}
lines.push('};');
lines.push('');
const file = lines.join('\n');
writeFileSync('src/lib/chatCipher/textModel.ts', file);
console.log(`wrote src/lib/chatCipher/textModel.ts (sha256 ${createHash('sha256').update(file).digest('hex').slice(0, 16)}…)`);
