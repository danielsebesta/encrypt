// Generates src/lib/icons.ts from src/lib/iconManifest.ts and the Solar
// Linear icons bundled in @iconify-json/solar. Run: pnpm run build:solar-icons
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ICONS } from '../src/lib/iconManifest.ts';

const root = new URL('../', import.meta.url);
const file = (p) => fileURLToPath(new URL(p, root));

const data = JSON.parse(readFileSync(file('node_modules/@iconify-json/solar/icons.json'), 'utf8'));

function resolve(name) {
  let current = name;
  for (let depth = 0; depth < 8; depth += 1) {
    if (data.icons[current]) return current;
    const alias = data.aliases?.[current];
    if (!alias?.parent) return null;
    current = alias.parent;
  }
  return null;
}

// Solar draws a few icons with a hairline as a filled path; the result still reads as Linear.
const FILLED_PATH_OK = new Set(['plain-linear']);

const problems = [];
const bodies = {};
const solarNames = new Map();

for (const [key, solarName] of Object.entries(ICONS)) {
  const iconName = `${solarName}-linear`;
  const resolved = resolve(iconName);
  if (!resolved) {
    problems.push(`${key}: "${iconName}" not found in @iconify-json/solar`);
    continue;
  }
  const body = data.icons[resolved]?.body;
  if (typeof body !== 'string' || !body.includes('stroke-width="1.5"') || (body.includes('fill="currentColor"') && !FILLED_PATH_OK.has(resolved))) {
    problems.push(`${key}: "${resolved}" is not a Solar Linear body (expected stroke-width="1.5" and no fill="currentColor")`);
    continue;
  }
  bodies[key] = body;
  const list = solarNames.get(resolved) ?? [];
  list.push(key);
  solarNames.set(resolved, list);
}

for (const [resolved, keys] of solarNames) {
  if (keys.length > 1) console.warn(`note: ${resolved} is shared by ${keys.join(', ')}`);
}

if (problems.length) {
  console.error(`build:solar-icons failed:\n${problems.map((p) => `  - ${p}`).join('\n')}`);
  process.exit(1);
}

const lines = Object.entries(bodies).map(([key, body]) => `  ${JSON.stringify(key)}: ${JSON.stringify(body)},`);
const out = `// Generated by scripts/build-solar-icons.mjs, do not edit.
import type { IconName } from './iconManifest';

export const SOLAR: Record<IconName, string> = {
${lines.join('\n')}
};

export const ICON_CREDIT = {
  name: 'Solar Icon Set',
  author: '480 Design',
  license: 'CC BY 4.0',
  licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',
  sourceUrl: 'https://github.com/480-Design/Solar-Icon-Set',
} as const;
`;

writeFileSync(file('src/lib/icons.ts'), out);
console.log(`build:solar-icons: wrote ${Object.keys(bodies).length} Solar Linear bodies to src/lib/icons.ts`);
